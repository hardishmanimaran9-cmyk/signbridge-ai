export function getSignByLabel(label: string): VerifiedSign | undefined {
  if (!label) return undefined;
  const upper = label.toUpperCase().trim();
  return VERIFIED_ISL_VOCABULARY.find((v) => v.label.toUpperCase() === upper);
}

export function getSignMessage(label: string, language: 'en' | 'ta'): string {
  const sign = getSignByLabel(label);
  if (!sign) {
    return label;
  }
  return language === 'ta' ? sign.tamilMessage : sign.englishMessage;
}
